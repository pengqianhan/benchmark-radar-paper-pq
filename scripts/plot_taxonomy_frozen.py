#!/usr/bin/env python3
r"""Draw Figure 6 from the frozen v0.11.0 release dates only.

This is the figure for the upstream Figure 6 submission (PR #59, option B). It
keeps the layout of the figure upstream already holds and changes one thing:
the undated column now shares the dated bars' vertical scale.

Input is `evidence/benchmark-taxonomy.jsonl`, the classified census before any
supplemental date is added. It holds all 1,283 source records; 615 carry a
release date and 668 do not. Panel A puts every dated record on its release
year and every undated record in one column. Panel B keeps the upstream rule
and series: shares only for years with enough dated records and a source mix
close to the pooled one.

The manuscript macros that describe this figure already exist upstream in
`taxonomy-trend-data.tex`. This script recomputes them with the same rule and
`--check` fails if they no longer match, so the caption cannot drift from the
figure. It writes `submission/figure6/taxonomy-trends.pdf`, which the submission
branch takes as `figures/taxonomy-trends.pdf`; the development build of that
file is unchanged.

Usage:
    python3 scripts/plot_taxonomy_frozen.py           # write the figure
    python3 scripts/plot_taxonomy_frozen.py --check   # also hold the macros to upstream
"""

import argparse
import json
import os
import sys
from collections import Counter, defaultdict
from datetime import datetime, timezone
from pathlib import Path

import matplotlib
from matplotlib import font_manager

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))
from taxonomy import L1 as L1_LABEL  # noqa: E402
from supplement_taxonomy_dates import BASE  # noqa: E402
from taxonomy_trends import MAX_MIX_DEVIATION, MIN_RELIABLE, TRACKED_FACETS, release_year  # noqa: E402
from plot_taxonomy import (  # noqa: E402
    DISCOVERY_CUTOFF, FACET_LABEL, FIG_WIDTH_IN, FONT_DIR, FONT_FAMILY,
    FS_AXIS, FS_PANEL, FS_TICK, L1_COLOR, display_order,
)

PAPER = Path(__file__).resolve().parents[1]
# Outside figures/, so the development build cannot mistake it for its own output.
OUT = PAPER / "submission" / "figure6" / "taxonomy-trends.pdf"

# The upstream manuscript's `taxonomy-trend-data.tex`. The submission changes
# no data file, so the figure must still satisfy these values.
UPSTREAM_MACROS = (
    "% Generated by scripts/taxonomy_trends.py. Do not edit by hand.\n"
    "\\newcommand{\\TaxonomyMinYearRecords}{30}\n"
    "\\newcommand{\\TaxonomyExcludedFromShares}{108}\n"
    "\\newcommand{\\TaxonomyMixAdjustment}{1.1}\n"
)
FROZEN_DATED, FROZEN_UNDATED = 615, 668

# Panel B's series, as upstream draws them.
TREND_SERIES = [
    ("facets", "interaction:agentic", "#8172B3", 2.6),
    ("l1", "coding_se", L1_COLOR["coding_se"], 1.8),
    ("l1", "multimodal_perception", L1_COLOR["multimodal_perception"], 1.8),
    ("l1", "knowledge_factuality", L1_COLOR["knowledge_factuality"], 1.8),
    ("l1", "applied_verticals", L1_COLOR["applied_verticals"], 1.8),
    ("facets", "modality:embodied", "#2E7D32", 1.6),
    ("facets", "operational:tool_calling", "#C2185B", 1.6),
]


def load_rows():
    return [json.loads(line) for line in BASE.read_text(encoding="utf-8").splitlines() if line]


def year_series(rows):
    """Year counts and shares over the frozen dates, by the upstream rule."""
    dated = [(release_year(row), row) for row in rows]
    undated = [row for year, row in dated if year is None]
    dated = [(year, row) for year, row in dated if year is not None]
    per_year = Counter(year for year, _ in dated)
    years = sorted(per_year)

    l1, facets = defaultdict(Counter), defaultdict(Counter)
    sources, source_agentic = defaultdict(Counter), defaultdict(Counter)
    for year, row in dated:
        l1[row["l1"]][year] += 1
        sources[row["source"]][year] += 1
        if "agentic" in row["interaction"]:
            source_agentic[row["source"]][year] += 1
        for axis, value in TRACKED_FACETS:
            if value in row[axis]:
                facets[f"{axis}:{value}"][year] += 1

    def series(counter):
        return {"counts": {y: counter.get(y, 0) for y in years},
                "share": {y: counter.get(y, 0) / per_year[y] for y in years},
                "total": sum(counter.values())}

    share_of_year = {s: {y: c.get(y, 0) / per_year[y] for y in years} for s, c in sources.items()}
    pooled = {s: sum(c.values()) / len(dated) for s, c in sources.items()}
    deviation = {y: 0.5 * sum(abs(share_of_year[s][y] - pooled[s]) for s in sources)
                 for y in years}
    reportable = [y for y in years
                  if per_year[y] >= MIN_RELIABLE and round(deviation[y], 4) <= MAX_MIX_DEVIATION]

    # The upstream sensitivity measure: each reported year's agentic share
    # reweighted to the second reported year's source mix.
    reference = {s: share_of_year[s][reportable[1]] for s in sources}
    worst = 0.0
    for y in reportable:
        crude = round(facets["interaction:agentic"][y] / per_year[y], 4)
        num = den = 0.0
        for s, c in sources.items():
            if c.get(y):
                num += round(reference[s], 4) * round(source_agentic[s].get(y, 0) / c[y], 4)
                den += round(reference[s], 4)
        worst = max(worst, abs(num / den - crude) * 100)
    excluded = sum(v for y, v in per_year.items() if y not in reportable)

    return {
        "population": len(rows), "dated": len(dated), "undated": len(undated),
        "undated_by_l1": Counter(row["l1"] for row in undated),
        "years": years, "per_year": per_year, "reportable": reportable,
        "l1": {k: series(v) for k, v in l1.items()},
        "facets": {k: series(v) for k, v in facets.items()},
        "macros": (
            "% Generated by scripts/taxonomy_trends.py. Do not edit by hand.\n"
            f"\\newcommand{{\\TaxonomyMinYearRecords}}{{{MIN_RELIABLE}}}\n"
            f"\\newcommand{{\\TaxonomyExcludedFromShares}}{{{excluded}}}\n"
            f"\\newcommand{{\\TaxonomyMixAdjustment}}{{{worst:.1f}}}\n"
        ),
    }


def draw(trends, order, path):
    axis = list(range(min(trends["years"]), max(trends["years"]) + 1))
    per_year, reportable = trends["per_year"], trends["reportable"]

    fig = plt.figure(figsize=(FIG_WIDTH_IN, 5.7))
    grid = fig.add_gridspec(2, 2, height_ratios=[1.2, 1.0], width_ratios=[11, 1.5],
                            hspace=1.00, wspace=0.06,
                            left=0.085, right=0.955, top=0.955, bottom=0.175)
    ax_top = fig.add_subplot(grid[0, 0])
    # One vertical scale for both columns, so the undated bar reads against the years.
    ax_undated = fig.add_subplot(grid[0, 1], sharey=ax_top)
    ax_mid = fig.add_subplot(grid[1, :])

    # Panel A: every record. Dated ones on the year axis, undated in their own
    # hatched column, both stacked by Level 1.
    bottom = {year: 0.0 for year in axis}
    undated_bottom = 0.0
    for l1 in order:
        series = trends["l1"].get(l1)
        values = [series["counts"].get(y, 0) for y in axis] if series else [0] * len(axis)
        ax_top.bar(axis, values, bottom=[bottom[y] for y in axis], color=L1_COLOR[l1],
                   width=0.74, label=f"{L1_LABEL[l1]} ({(series or {}).get('total', 0)})",
                   edgecolor="white", linewidth=0.4)
        for year, value in zip(axis, values):
            bottom[year] += value
        count = trends["undated_by_l1"].get(l1, 0)
        ax_undated.bar([0], [count], bottom=[undated_bottom], color=L1_COLOR[l1],
                       width=0.72, edgecolor="white", linewidth=0.4, hatch="//")
        undated_bottom += count
    assert undated_bottom == trends["undated"]
    peak = max(max(bottom.values()), undated_bottom)
    for year in axis:
        if per_year.get(year):
            ax_top.text(year, bottom[year] + peak * 0.02, str(per_year[year]),
                        ha="center", va="bottom", fontsize=6.0, color="#333333")
    ax_undated.text(0, undated_bottom + peak * 0.02, str(trends["undated"]), ha="center",
                    va="bottom", fontsize=6.5, color="#333333")
    ax_undated.set_xticks([0])
    ax_undated.set_xticklabels(["no release\ndate"], fontsize=FS_TICK)
    ax_undated.set_xlim(-0.62, 0.62)
    ax_undated.yaxis.tick_right()
    ax_undated.tick_params(axis="y", labelsize=6.0)
    ax_undated.spines[["top", "left"]].set_visible(False)
    ax_undated.grid(axis="y", alpha=0.25, linewidth=0.6)
    ax_undated.set_axisbelow(True)
    ax_top.set_xticks(axis)
    ax_top.set_xticklabels([str(y) for y in axis], fontsize=FS_TICK, rotation=45)
    ax_top.set_xlim(min(axis) - 0.7, max(axis) + 0.7)
    ax_top.set_ylim(0, peak * 1.10)
    ax_top.set_ylabel("Benchmarks", fontsize=FS_AXIS)
    ax_top.tick_params(axis="y", labelsize=6.0)
    ax_top.set_title(
        f"A · Release year of all {trends['population']:,} records, by Level 1",
        fontsize=FS_PANEL, fontweight="normal", loc="left", pad=6,
    )
    ax_top.spines[["top", "right"]].set_visible(False)
    ax_top.grid(axis="y", alpha=0.25, linewidth=0.6)
    ax_top.set_axisbelow(True)

    # Panel B: shares only where the base supports them.
    for kind, key, color, width in TREND_SERIES:
        values = [trends[kind][key]["share"][y] for y in reportable]
        label = FACET_LABEL.get(key, L1_LABEL.get(key, key))
        ax_mid.plot(reportable, values, color=color, linewidth=width * 0.65, marker="o",
                    markersize=3.5, label=label, zorder=3, alpha=0.95)
        ax_mid.annotate(f"{values[-1] * 100:.0f}%", xy=(reportable[-1], values[-1]),
                        xytext=(6, 0), textcoords="offset points", va="center",
                        fontsize=6.5, color=color)
    ax_mid.set_xticks(reportable)
    ax_mid.set_xticklabels([f"{y}\nn={per_year[y]}" for y in reportable], fontsize=FS_TICK)
    ax_mid.set_xlim(reportable[0] - 0.35, reportable[-1] + 0.55)
    ax_mid.set_ylim(0, 0.35)
    ax_mid.yaxis.set_major_formatter(lambda v, _: f"{v * 100:.0f}%")
    ax_mid.tick_params(axis="y", labelsize=FS_TICK)
    ax_mid.set_ylabel("Share of dated records", fontsize=FS_AXIS)
    ax_mid.set_title(
        "B · Selected classes and facets, over the years whose share the evidence supports",
        fontsize=FS_PANEL, fontweight="normal", loc="left", pad=6,
    )
    ax_mid.spines[["top", "right"]].set_visible(False)
    ax_mid.grid(axis="y", alpha=0.25, linewidth=0.6)
    ax_mid.set_axisbelow(True)

    ax_top.legend(loc="upper center", bbox_to_anchor=(0.5, -0.34), ncol=3,
                  fontsize=6.2, frameon=False, columnspacing=1.2, handlelength=1.2)
    ax_mid.legend(loc="upper center", bbox_to_anchor=(0.5, -0.22), ncol=3,
                  fontsize=6.2, frameon=False, columnspacing=1.2, handlelength=1.2)

    fig.savefig(path)
    plt.close(fig)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="fail unless the recomputed macros equal upstream's")
    parser.add_argument("--out", type=Path, default=OUT, help=f"default: {OUT.relative_to(PAPER)}")
    args = parser.parse_args()
    os.environ["SOURCE_DATE_EPOCH"] = str(int(
        datetime.fromisoformat(DISCOVERY_CUTOFF).replace(tzinfo=timezone.utc).timestamp()
    ))

    font_manager.fontManager.ttflist = [
        entry for entry in font_manager.fontManager.ttflist if entry.name != FONT_FAMILY
    ]
    for style in ("Regular", "Italic"):
        font_manager.fontManager.addfont(FONT_DIR / f"LiberationSans-{style}.ttf")
    plt.rcdefaults()
    plt.rcParams.update({
        "font.family": "sans-serif",
        "font.sans-serif": [FONT_FAMILY],
        "font.weight": "normal",
        "axes.titleweight": "normal",
        "axes.labelweight": "normal",
        "pdf.fonttype": 42,
    })

    rows = load_rows()
    trends = year_series(rows)
    assert trends["population"] == len(rows) == 1283, "the figure must draw the whole census"
    assert (trends["dated"], trends["undated"]) == (FROZEN_DATED, FROZEN_UNDATED), \
        "only frozen v0.11.0 release dates may enter this figure"
    if args.check and trends["macros"] != UPSTREAM_MACROS:
        print("recomputed macros differ from upstream taxonomy-trend-data.tex:")
        print(trends["macros"])
        return 1

    args.out.parent.mkdir(parents=True, exist_ok=True)
    draw(trends, display_order(rows), args.out)
    print(f"taxonomy-trends (frozen) : {trends['dated']} dated over "
          f"{trends['years'][0]}-{trends['years'][-1]}, {trends['undated']} undated on the same scale; "
          f"shares over {', '.join(map(str, trends['reportable']))}")
    print(f"    {args.out}  {args.out.stat().st_size // 1024} KB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
